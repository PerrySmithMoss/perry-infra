func writeFixture(t *testing.T, root, name, contents string) {
	t.Helper()
	path := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
}

func snapshotFixture(t *testing.T) (string, map[string]string) {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"docker-compose.stack.yaml": "services:\r\n",
		"postgres/pg_hba.conf":      "\x00\xff\n",
		"docker-proxy/haproxy.cfg":  "",
	}
	for name, contents := range files {
		writeFixture(t, root, name, contents)
	}
	return root, files
}

func TestFingerprintCompatibility(t *testing.T) {
	root, files := snapshotFixture(t)

	// Generated by the original Python broker from these exact file bytes.
	const want = "fbd8205519c616364c0d4a81be53bd96970f39f6411093b8d7ed6fbee4fee321"
	if got, err := fingerprint(root); err != nil || got != want {
		t.Fatalf("fingerprint = %q, %v, want %q", got, err, want)
	}
	for name, contents := range files {
		writeFixture(t, root, name, "changed")
		if got, err := fingerprint(root); err != nil || got == want {
			t.Fatalf("changing %s produced fingerprint %q, %v", name, got, err)
		}
		writeFixture(t, root, name, contents)
	}
	if err := os.Remove(filepath.Join(root, "postgres/pg_hba.conf")); err != nil {
		t.Fatal(err)
	}
	if _, err := fingerprint(root); err == nil {
		t.Fatal("accepted a snapshot with a missing file")
	}
}

func TestSSHCommand(t *testing.T) {
	digest := strings.Repeat("a", 64)
	command := "infrastructure " + digest
	want := []string{"sudo", "-n", "--", "/usr/local/libexec/perry-infra-release", digest}
	if got, err := sshArgs(command); err != nil || !slices.Equal(got, want) {
		t.Fatalf("sshArgs(%q) = %q, %v, want %q", command, got, err, want)
	}
	for _, invalid := range []string{
		"", "id", "docker system dial-stdio", "internal-sftp", "infrastructure ../../tmp",
		command + ";id", command + "\n", command + " extra", command + "a",
		"infrastructure  " + digest, "infrastructure\t" + digest, "infrastructure " + strings.ToUpper(digest),
		"infrastructure " + digest[:63],
	} {
		if _, err := sshArgs(invalid); err == nil {
			t.Errorf("accepted SSH command %q", invalid)
		}
	}
}

func TestACMEEnv(t *testing.T) {
	const want = "ACME_EMAIL=owner+acme@example.com"
	if got, err := acmeEnv(strings.NewReader(`["OTHER=value","ACME_EMAIL=owner+acme@example.com"]`)); err != nil || got != want {
		t.Fatalf("acmeEnv = %q, %v, want %q", got, err, want)
	}
	for _, invalid := range []string{
		`["OTHER=value"]`, `["ACME_EMAIL="]`, `["ACME_EMAIL=x;id"]`,
		`["ACME_EMAIL=x\n"]`, `["ACME_EMAIL=$(id)"]`, `{}`,
	} {
		if _, err := acmeEnv(strings.NewReader(invalid)); err == nil {
			t.Errorf("accepted Traefik environment %q", invalid)
		}
	}
}

func TestDeployRequiresFingerprintAndExclusiveLock(t *testing.T) {
	root, _ := snapshotFixture(t)
	lockName := filepath.Join(root, "release.lock")
	writeFixture(t, root, "deployment.env", "touch sourced; exit 0\n")
	digest, err := fingerprint(root)
	if err != nil {
		t.Fatal(err)
	}

	if err := deploySnapshot(root, lockName, strings.Repeat("0", 64), time.Second); err == nil {
		t.Fatal("accepted a mismatched fingerprint")
	}
	lock, err := os.Open(lockName)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { lock.Close() })
	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		t.Fatal(err)
	}
	if err := deploySnapshot(root, lockName, digest, time.Second); !errors.Is(err, syscall.EWOULDBLOCK) {
		t.Fatalf("expected lock contention, got %v", err)
	}
	marker := filepath.Join(root, "sourced")
	if _, err := os.Stat(marker); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("rejected release sourced deployment.env: %v", err)
	}

	if err := syscall.Flock(int(lock.Fd()), syscall.LOCK_UN); err != nil {
		t.Fatal(err)
	}
	if err := deploySnapshot(root, lockName, digest, time.Second); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(marker); err != nil {
		t.Fatal(err)
	}
}

func TestDeployTimeoutStopsChildrenAndReleasesLock(t *testing.T) {
	root, _ := snapshotFixture(t)
	lockName := filepath.Join(root, "release.lock")
	digest, err := fingerprint(root)
	if err != nil {
		t.Fatal(err)
	}
	writeFixture(t, root, "deployment.env", "touch started; (sleep 2; touch survived) & wait; exit 0\n")

	if err := deploySnapshot(root, lockName, digest, time.Second); err == nil {
		t.Fatal("deployment should time out")
	}
	if _, err := os.Stat(filepath.Join(root, "started")); err != nil {
		t.Fatalf("deployment fixture did not start: %v", err)
	}
	writeFixture(t, root, "deployment.env", "exit 0\n")
	if err := deploySnapshot(root, lockName, digest, time.Second); err != nil {
		t.Fatalf("could not retry after timeout: %v", err)
	}
	time.Sleep(2 * time.Second)
	if _, err := os.Stat(filepath.Join(root, "survived")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("timed-out deployment left a child running: %v", err)
	}
}
