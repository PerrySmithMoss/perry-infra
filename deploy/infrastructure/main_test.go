func TestFingerprintCompatibility(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"docker-compose.stack.yaml": "services:\r\n",
		"postgres/pg_hba.conf":      "\x00\xff\n",
		"docker-proxy/haproxy.cfg":  "",
	}
	write := func(name, contents string) {
		t.Helper()
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	for name, contents := range files {
		write(name, contents)
	}

	// Generated by the original Python broker from these exact file bytes.
	const want = "fbd8205519c616364c0d4a81be53bd96970f39f6411093b8d7ed6fbee4fee321"
	if got, err := fingerprint(root); err != nil || got != want {
		t.Fatalf("fingerprint = %q, %v, want %q", got, err, want)
	}
	for name, contents := range files {
		write(name, "changed")
		if got, err := fingerprint(root); err != nil || got == want {
			t.Fatalf("changing %s produced fingerprint %q, %v", name, got, err)
		}
		write(name, contents)
	}
	if err := os.Remove(filepath.Join(root, "postgres/pg_hba.conf")); err != nil {
		t.Fatal(err)
	}
	if _, err := fingerprint(root); err == nil {
		t.Fatal("accepted a snapshot with a missing file")
	}
}

func TestSSHCommand(t *testing.T) {
	digest := strings.Repeat("a", 64)
	command := "infrastructure " + digest
	want := []string{"sudo", "-n", "--", "/usr/local/libexec/perry-infra-release", digest}
	if got, err := sshArgs(command); err != nil || !slices.Equal(got, want) {
		t.Fatalf("sshArgs(%q) = %q, %v, want %q", command, got, err, want)
	}
	for _, invalid := range []string{
		"", "id", "docker system dial-stdio", "internal-sftp", "infrastructure ../../tmp",
		command + ";id", command + "\n", command + " extra", command + "a",
		"infrastructure  " + digest, "infrastructure\t" + digest, "infrastructure " + strings.ToUpper(digest),
		"infrastructure " + digest[:63],
	} {
		if _, err := sshArgs(invalid); err == nil {
			t.Errorf("accepted SSH command %q", invalid)
		}
	}
}

func TestACMEEnv(t *testing.T) {
	const want = "ACME_EMAIL=owner+acme@example.com"
	if got, err := acmeEnv(strings.NewReader(`["OTHER=value","ACME_EMAIL=owner+acme@example.com"]`)); err != nil || got != want {
		t.Fatalf("acmeEnv = %q, %v, want %q", got, err, want)
	}
	for _, invalid := range []string{
		`["OTHER=value"]`, `["ACME_EMAIL="]`, `["ACME_EMAIL=x;id"]`,
		`["ACME_EMAIL=x\n"]`, `["ACME_EMAIL=$(id)"]`, `{}`,
	} {
		if _, err := acmeEnv(strings.NewReader(invalid)); err == nil {
			t.Errorf("accepted Traefik environment %q", invalid)
		}
	}
}
