func TestRedisRotationURLCannotChangeTheTargetOrInjectConfig(t *testing.T) {
	password := strings.Repeat("a", 64)
	valid := "redis://netdata:" + password + "@perry-infra_redis:6379/0"
	if got, err := redisURLPassword([]byte(valid)); err != nil || got != password {
		t.Fatal("rejected the dedicated monitoring URL")
	}
	for _, invalid := range []string{
		strings.Replace(valid, "netdata:", "admin:", 1),
		strings.Replace(valid, "perry-infra_redis", "other-host", 1),
		strings.Replace(valid, "/0", "/1", 1),
		valid + "?option=unreviewed", valid + "#fragment",
		strings.Replace(valid, password, "bad%27%0Avalue", 1),
	} {
		if _, err := redisURLPassword([]byte(invalid)); err == nil {
			t.Fatal("accepted a different identity/target or unsafe config value")
		}
	}
}

func TestCollectorEvidenceRequiresRepeatedNumericSamples(t *testing.T) {
	chart := "CHART 'postgres_private.connections' '' 'Connection usage' 'connections' 'connections' 'postgres.connections_usage' line 1 5\n"
	cycle := "BEGIN postgres_private.connections\nSET used = 0\nEND\n"
	if got := collectedContexts(chart + cycle + cycle)["postgres.connections_usage"]; got != 2 {
		t.Fatalf("zero is valid metric evidence, got %d cycles", got)
	}
	for _, stream := range []string{
		chart, chart + "BEGIN postgres_private.connections\nSET used = NaN\nEND\n",
		chart + "BEGIN postgres_private.connections\nSET used = 2\n", // incomplete cycle
	} {
		if len(collectedContexts(stream)) != 0 {
			t.Fatal("accepted chart declarations, NaN or an unfinished update as metric evidence")
		}
	}
	otherChart := strings.ReplaceAll(chart, "connections'", "another'")
	otherCycle := strings.ReplaceAll(cycle, "connections\n", "another\n")
	if got := collectedContexts(chart + cycle + otherChart + otherCycle)["postgres.connections_usage"]; got != 1 {
		t.Fatal("counted different charts as repeated samples")
	}
	modern := chart + "BEGIN2 postgres_private.connections 5 0 0\nSET2 used 1 1 ''\nEND2\n"
	if got := collectedContexts(modern)["postgres.connections_usage"]; got != 1 {
		t.Fatal("failed to read the current plugin protocol")
	}
	if got := collectedContexts(strings.ReplaceAll(chart+cycle+cycle, "\n", "\r\n"))["postgres.connections_usage"]; got != 2 {
		t.Fatal("failed to read terminal debug output")
	}
}

