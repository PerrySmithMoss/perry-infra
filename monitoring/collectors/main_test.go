func TestMetricsACLPreservesExistingUsersAndDeniesData(t *testing.T) {
	current := "# Preserve comments too\nuser default reset off\nuser app on #application-hash ~app:* +get +set\nuser admin on #admin-hash ~* +@all\n"
	secret := strings.Repeat("a", 64)
	got, err := metricsACL(current, secret)
	if err != nil {
		t.Fatal(err)
	}
	want := current + "\n" + fmt.Sprintf("user netdata reset on #%x resetkeys resetchannels -@all +ping +info +hello +client|setinfo\n", sha256.Sum256([]byte(secret)))
	if got != want || strings.Contains(got, secret) {
		t.Fatal("changed an existing ACL or exposed the plaintext password")
	}
	if _, err := metricsACL(got, secret); err == nil {
		t.Fatal("silently replaced an existing monitoring identity")
	}
	if _, err := metricsACL("", secret); err == nil {
		t.Fatal("accepted an empty existing ACL")
	}
}

func TestTerminalCaptureStopsItsForegroundProcess(t *testing.T) {
	if runtime.GOOS != "linux" {
		t.Skip("uses Debian util-linux script")
	}
	if _, err := exec.LookPath("script"); err != nil {
		t.Skip("requires util-linux script")
	}
	path := filepath.Join(t.TempDir(), "child.pid")
	// TempDir is generated by Go, with no shell metacharacters or spaces.
	_, _ = captureCommand(nil, true, 4*time.Second, "env", "SHELL=/bin/sh", "script", "--quiet", "--return", "--command", "echo $$ > "+path+"; exec sleep 30", "/dev/null")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(data)))
	if err != nil {
		t.Fatal(err)
	}
	if err := syscall.Kill(pid, 0); !errors.Is(err, syscall.ESRCH) {
		syscall.Kill(pid, syscall.SIGKILL)
		t.Fatal("terminal capture left its foreground process alive")
	}
}

func TestAliasPreservesHostsAndRejectsConflicts(t *testing.T) {
	current := "127.0.0.1 localhost\n::1 localhost ip6-localhost\n# perry-infra_postgres in a comment\n"
	got, err := hostsWithAlias(current)
	if err != nil || !strings.HasPrefix(got, current) || !strings.Contains(got, "127.0.0.1 perry-infra_postgres # perry-private-metrics") {
		t.Fatal("did not preserve hosts while adding the certificate hostname")
	}
	for _, text := range []string{got, "10.0.0.1 another perry-infra_postgres # comment\n"} {
		if _, err := hostsWithAlias(text); err == nil {
			t.Fatal("accepted an existing hostname mapping")
		}
	}
}

