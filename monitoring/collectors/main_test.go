func TestDiagnosticsNeverEchoPrivateLogContents(t *testing.T) {
	private := "user admin on #private-credential-hash\npostgres://netdata_monitor:private-password@host/db\n"
	log := private + "FAIL: agent not claimed/online. Check Cloud setup and outbound HTTPS.\n" + private
	diagnoses := logDiagnoses(log)
	if len(diagnoses) != 1 || strings.Contains(strings.Join(diagnoses, "\n"), "private-") {
		t.Fatal("diagnostic extraction exposed private data or lost the known failure")
	}
	if len(logDiagnoses(private)) != 0 {
		t.Fatal("printed unrecognized private log content")
	}
}

func TestSnapshotDiagnosticsUseBrokerOutsideCheckout(t *testing.T) {
	root, snapshot := t.TempDir(), t.TempDir()
	broker := filepath.Join(t.TempDir(), "perry-infra-release")
	// A tiny broker fixture reads each directory's fingerprint. It cannot deploy.
	if err := os.WriteFile(broker, []byte("#!/bin/sh\nset -eu\n[ \"$#\" -eq 2 ] && [ \"$1\" = fingerprint ]\ncat -- \"$2/fingerprint\"\n"), 0o700); err != nil {
		t.Fatal(err)
	}
	for _, directory := range []string{root, snapshot} {
		if err := os.WriteFile(filepath.Join(directory, "fingerprint"), []byte(strings.Repeat("a", 64)+"\n"), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := verifySnapshot(root, broker, snapshot); err != nil {
		t.Fatalf("matching snapshots require no checkout-local binary: %v", err)
	}
	if err := os.WriteFile(filepath.Join(snapshot, "fingerprint"), []byte(strings.Repeat("b", 64)+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := verifySnapshot(root, broker, snapshot); err == nil || !strings.Contains(err.Error(), "differs") {
		t.Fatalf("expected snapshot mismatch, got %v", err)
	}
	for _, test := range []struct{ name, directory string }{{"checkout", root}, {"installed", snapshot}} {
		t.Run("missing "+test.name, func(t *testing.T) {
			directory := test.directory
			if err := os.Remove(filepath.Join(directory, "fingerprint")); err != nil {
				t.Fatal(err)
			}
			if err := verifySnapshot(root, broker, snapshot); err == nil || !strings.Contains(err.Error(), "cannot fingerprint") {
				t.Fatalf("failed fingerprint must not pass: %v", err)
			}
			if err := os.WriteFile(filepath.Join(directory, "fingerprint"), []byte(strings.Repeat("a", 64)+"\n"), 0o600); err != nil {
				t.Fatal(err)
			}
		})
	}
}
