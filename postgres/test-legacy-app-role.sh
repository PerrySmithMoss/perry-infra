#!/bin/sh
set -eu

# Uses a disposable server selected by PGHOST and the remaining libpq variables.
cd "$(dirname "$0")"
psql -X -v ON_ERROR_STOP=1 -d postgres <<'SQL'
CREATE DATABASE chinwag;
CREATE DATABASE vita_track;
SQL

for target in chinwag:chinwag_app vita_track:vita_track_app; do
  database=${target%:*}
  role=${target#*:}
  psql -X -v ON_ERROR_STOP=1 -d "$database" <<'SQL'
CREATE TABLE "_prisma_migrations" (id text PRIMARY KEY);
CREATE TABLE messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body text);
INSERT INTO messages (body) VALUES ('before rotation');
CREATE SEQUENCE unowned_sequence;
SQL
  psql -X -v ON_ERROR_STOP=1 -v app_role="$role" -d "$database" -f legacy-app-role.sql
  psql -X -v ON_ERROR_STOP=1 -v app_role="$role" -d "$database" -f legacy-app-role.sql
  psql -X -v ON_ERROR_STOP=1 -v app_role="$role" -d "$database" <<'SQL'
SET ROLE :"app_role";
ALTER TABLE messages ADD COLUMN checked boolean;
INSERT INTO messages (body, checked) VALUES ('after rotation', true);
ALTER SEQUENCE unowned_sequence RESTART WITH 2;
CREATE TABLE new_migration_object (id integer);
DO $$
BEGIN
  IF (SELECT count(*) FROM messages) <> 2 THEN RAISE EXCEPTION 'Existing data did not survive'; END IF;
END $$;
SQL
done

if psql -X -v ON_ERROR_STOP=1 -v app_role=vita_track_app -d chinwag -f legacy-app-role.sql; then
  echo 'Accepted an app role for the wrong database' >&2
  exit 1
fi

test "$(psql -X -At -d postgres -c "SELECT has_database_privilege('chinwag_app','vita_track','CONNECT'), has_database_privilege('vita_track_app','chinwag','CONNECT')")" = 'f|f'
test "$(psql -X -At -d postgres -c "SELECT count(*) FROM pg_roles WHERE rolname IN ('chinwag_app','vita_track_app') AND rolcanlogin AND NOT (rolsuper OR rolcreaterole OR rolcreatedb OR rolreplication OR rolbypassrls)")" = 2
